# Marginalized zero-inflated Poisson regression Use mzip (mcount) With (In) R Software
install.packages("mcount")
library("mcount")
# Estimate Marginalized zero-inflated Poisson regression Use mzip (mcount) With (In) R Software
mzip_r = read.csv("https://raw.githubusercontent.com/timbulwidodostp/mzip_r/main/mzip_r/mzip_r.csv",sep = ";")
mzip = mzip(formula = mzip ~ mzip_1 + mzip_2 + mzip_3 + mzip_4, data = mzip_r)
summary(mzip)
